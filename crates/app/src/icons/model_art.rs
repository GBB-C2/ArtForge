//! The modeling tools' artwork in the original 24 × 24 SVG coordinate system.
//! Paths retain their paint order, including translucent fills beneath strokes.

#[derive(Clone, Copy)]
pub(super) enum Command {
    M(f32, f32),
    L(f32, f32),
    Q(f32, f32, f32, f32),
    C(f32, f32, f32, f32, f32, f32),
    Z,
}

pub(super) enum Shape {
    Path(&'static [Command]),
    Oval(f32, f32, f32, f32),
}

#[derive(Clone, Copy)]
pub(super) enum Style {
    Edge, Minor, Action, Cable, Facet, Body, Wash, Node, Hot,
}

pub(super) struct Layer(pub(super) Style, pub(super) Shape);

